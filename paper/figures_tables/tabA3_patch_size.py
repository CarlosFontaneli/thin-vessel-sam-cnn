"""Table VII (tab:patch_size): compact MedSAM, best validation Dice reached by the search for each patch size and
dataset.

For each dataset and patch size: the number of trials that used the patch size and reached at least one
validation, and the highest validation Dice any of them reached (maximum over the validations of each trial,
pruned trials included). Trials that ran out of GPU memory before their first validation (``train.log``:
"failed due to recoverable error: OutOfMemoryError") are counted apart; the script checks that every trial
without a validation is one of them or a failed trial (one on DRIVE, which crashed after 8 s and was rerun).
The other hyperparameters vary between trials, so a value is the best the search found with that patch size,
not the effect of the patch size alone.
Source: ``search_trials.csv`` (via ``common.load_trials``; from the compact-MedSAM studies and their ``train.log``).
Output: ``paper/manuscript/figures/tabA3_patch_size.tex``.
"""

from common import DATASET_LABELS, DATASETS, load_trials, pd, save_values, selected_trial, write_tex

CONFIG = "medsam_compact_scratch"
PATCHES = [1, 2, 4, 8, 16]
FINISHED = {"COMPLETE", "PRUNED", "FAIL"}


def main() -> None:
    rows = []
    for ds in DATASETS:
        t = load_trials(CONFIG, ds)
        oom = set(t.loc[t["out_of_memory"], "number"].astype(int))
        t = t[t["state"].isin(FINISHED)]
        no_val = set(t.loc[t["best_val_dice"].isna() & (t["state"] != "FAIL"), "number"].astype(int))
        if not no_val <= oom:
            raise ValueError(f"{ds}: trials without validation that did not run out of memory: {no_val - oom}")
        sel = selected_trial(CONFIG, ds)
        sel_patch = int(t.loc[t["number"] == sel, "patch_size"].iloc[0])
        for p in PATCHES:
            sub = t[t["patch_size"] == p]
            rows.append(
                {
                    "dataset": ds,
                    "patch_size": p,
                    "trials": len(sub),
                    "trials_with_validation": int(sub["best_val_dice"].notna().sum()),
                    "trials_out_of_memory": int(sub["number"].astype(int).isin(oom).sum()),
                    "best_val_dice": sub["best_val_dice"].max() if len(sub) else float("nan"),
                    "selected": p == sel_patch,
                }
            )
    df = pd.DataFrame(rows)
    save_values(df, "tabA3_patch_size")
    best = df.loc[df.groupby("dataset")["best_val_dice"].idxmax()]
    if not best["selected"].all():
        raise ValueError("The best patch size per dataset is not the selected run's patch size.")

    body = []
    for p in PATCHES:
        cells = []
        for ds in DATASETS:
            r = df[(df["dataset"] == ds) & (df["patch_size"] == p)].iloc[0]
            if r["trials"] == 0:  # 2 px on DRIVE: left out of the search after it ran out of GPU memory in an
                # earlier test run (not recorded in the study database)
                cells += ["0", "OOM"]
                continue
            if r["trials_with_validation"] == 0:
                cells += ["0", "OOM"]  # no trial reached a validation; one value per column keeps the alignment
                continue
            val = f"{100 * r['best_val_dice']:.1f}" if pd.notna(r["best_val_dice"]) else "--"
            cells += [str(r["trials_with_validation"]), rf"\textbf{{{val}}}" if r["selected"] else val]
        body.append(f"{p} & " + " & ".join(cells) + r" \\")
    header1 = " & ".join(rf"\multicolumn{{2}}{{c}}{{{DATASET_LABELS[d]}}}" for d in DATASETS)
    cmid = " ".join(rf"\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(DATASETS)))
    tex = rf"""% Generated by paper/figures_tables/tabA3_patch_size.py -- do not edit by hand.
% Source: results/search_trials.csv (compact-MedSAM studies).
\begin{{table}}[tbp]
\caption{{Patch size in the search of compact \medsam{{}}: trials that reached a validation (Tr.) and their best
validation Dice (\%). Bold: best, the selected patch size; OOM: every trial ran out of GPU memory.}}
\label{{tab:patch_size}}
\begin{{ruledtabular}}
\begin{{tabular}}{{c{"rr" * len(DATASETS)}}}
 & {header1} \\
{cmid}
Patch (px) & {" & ".join("Tr. & Dice" for _ in DATASETS)} \\
\midrule
{chr(10).join(body)}
\end{{tabular}}
\end{{ruledtabular}}
\end{{table}}
"""
    write_tex("tabA3_patch_size", tex)


if __name__ == "__main__":
    main()
