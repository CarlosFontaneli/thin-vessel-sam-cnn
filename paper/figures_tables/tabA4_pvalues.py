"""Tables IX and X (tab:pvalues, tab:pvalues_other): Holm-adjusted p-values of every pairwise Wilcoxon test.

Two tables, one per kind of family of ``all_tests.csv`` (computed by
``paper/statistics/paper_wilcoxon.py``; this script only formats it):
  * ``tab:pvalues``: family F1, the 36 pairs of the nine configurations, per dataset and metric (Dice, thin-vessel
    recall, thin-vessel precision);
  * ``tab:pvalues_other``: family F2, the 10 pairs of the five models of Table II for the overall centerline recall
    and precision, and family F3, the upscaled against the padded protocol of MedSAM (Table IV).
Significant p-values (< 0.05) carry a superscript + (-) when the per-image differences favour the first
(second) configuration of the pair: the direction of the test, the sign of the Hodges-Lehmann estimate. It can differ
from the sign of the difference of means (two cells: ConvUNeXt on DRIVE, Dice); the caption says so.
Output: ``paper/manuscript/figures/tabA4_pvalues.tex``.
"""

from common import (
    ALPHA,
    DATASET_LABELS,
    DATASETS,
    fmt_p,
    load_tests,
    pd,
    save_values,
    write_tex,
)

SHORT = {
    "LW-Net": "LW",
    "ConvUNeXt": "CU",
    "ConvNeXt": "CN",
    "LiteMedSAM FT": "LM",
    "LiteMedSAM scratch": "LM-S",
    "compact LiteMedSAM": "LM-C",
    "MedSAM FT": "M",
    "MedSAM scratch": "M-S",
    "compact MedSAM": "M-C",
}
F1_METRICS = [
    ("dice", "Dice"),
    ("thin_vessel_recall", r"$\thinrecall$"),
    ("thin_vessel_precision", r"$P_{\mathrm{thin}}$"),
]
F2_METRICS = [("centerline_recall", r"$R_{\mathrm{cl}}$"), ("centerline_precision", r"$P_{\mathrm{cl}}$")]
ABBREV = (
    r"LW: \lwnet{}; CU: \convunext{}; CN: \convnext{}; LM, LM-S, LM-C: \litemedsam{} fine-tuned, from "
    r"scratch and compact; M, M-S, M-C: \medsam{} fine-tuned, from scratch and compact"
)
ABBREV_FIVE = (
    r"LW: \lwnet{}; CU: \convunext{}; CN: \convnext{}; LM: \litemedsam{} fine-tuned; "
    r"M: \medsam{} fine-tuned"
)


def cell(r: pd.Series) -> str:
    text = fmt_p(r["p_holm"])
    if r["p_holm"] >= ALPHA:
        return text
    sign = "+" if r["hodges_lehmann"] > 0 else "-"
    return rf"{text}$^{{{sign}}}$"


def grid(tests: pd.DataFrame, family: str, metrics, label_fn) -> tuple:
    """Rows of a p-value table: one per pair (order of the test file), one column per dataset and metric."""
    sub = tests[tests["family"].str.startswith(family)]
    pairs = sub[["A", "B"]].drop_duplicates().itertuples(index=False, name=None)
    body = []
    for a, b in pairs:
        cells = []
        for ds in DATASETS:
            for metric, _ in metrics:
                r = sub[(sub["A"] == a) & (sub["B"] == b) & (sub["dataset"] == ds) & (sub["metric"] == metric)]
                if len(r) != 1:
                    raise ValueError(f"Missing test {a} vs {b}, {ds}, {metric}.")
                cells.append(cell(r.iloc[0]))
        body.append(f"{label_fn(a, b)} & " + " & ".join(cells) + r" \\")
    return body


def header(metrics, first: str) -> str:
    k = len(metrics)
    h1 = " & ".join(rf"\multicolumn{{{k}}}{{c}}{{{DATASET_LABELS[d]}}}" for d in DATASETS)
    cmid = " ".join(rf"\cmidrule(lr){{{2 + k * i}-{1 + k * (i + 1)}}}" for i in range(len(DATASETS)))
    h2 = " & ".join(lab for _ in DATASETS for _, lab in metrics)
    return f" & {h1} \\\\\n{cmid}\n{first} & {h2} \\\\"


def main() -> None:
    tests = load_tests()
    save_values(
        tests[
            [
                "family",
                "dataset",
                "metric",
                "A",
                "B",
                "n",
                "mean_a",
                "mean_b",
                "p_raw",
                "p_holm",
                "significant",
                "verdict",
            ]
        ],
        "tabA4_pvalues",
    )
    pair_label = lambda a, b: f"{SHORT[a]} vs {SHORT[b]}"  # noqa: E731
    f1 = grid(tests, "F1", F1_METRICS, pair_label)
    f2 = grid(tests, "F2", F2_METRICS, pair_label)

    f3 = tests[tests["family"].str.startswith("F3")]
    f3_rows = []
    for regime, name in (("Fine-tuned", "MedSAM FT"), ("From scratch", "MedSAM scratch")):
        cells = []
        for ds in ("drive", "vessmap"):
            for metric, _ in F1_METRICS:
                r = f3[(f3["A"] == f"{name} upscaled") & (f3["dataset"] == ds) & (f3["metric"] == metric)]
                if len(r) != 1:
                    raise ValueError(f"Missing padding test {name}, {ds}, {metric}.")
                cells.append(cell(r.iloc[0]))
        f3_rows.append(f"{regime} & " + " & ".join(cells) + r" \\")
    f3_h1 = " & ".join(rf"\multicolumn{{3}}{{c}}{{{DATASET_LABELS[d]}}}" for d in ("drive", "vessmap"))
    f3_h2 = " & ".join(lab for _ in range(2) for _, lab in F1_METRICS)

    tex = rf"""% Generated by paper/figures_tables/tabA4_pvalues.py -- do not edit by hand.
% Source: outputs/statistics/all_tests.csv (paper/statistics/paper_wilcoxon.py).
\begin{{table*}}[tbp]
\caption{{Holm-adjusted p-values of the pairwise tests of the nine configurations; $^{{+}}$ ($^{{-}}$): $p < 0.05$
and the
first (second) configuration is better (sign of the Hodges--Lehmann estimate). \convunext{{}} on
DRIVE (Dice): one failed image makes the test direction differ from the means against M-S and M-C. {ABBREV}.}}
\label{{tab:pvalues}}
\scriptsize
\begin{{ruledtabular}}
\begin{{tabular}}{{l{"c" * (len(DATASETS) * len(F1_METRICS))}}}
{header(F1_METRICS, "Pair")}
\midrule
{chr(10).join(f1)}
\end{{tabular}}
\end{{ruledtabular}}
\end{{table*}}

\begin{{table*}}[tbp]
\caption{{Holm-adjusted p-values for Table~\ref{{tab:global_baseline}} (top; {ABBREV_FIVE}) and
Table~\ref{{tab:padding}} (bottom); $^{{+}}$ ($^{{-}}$): $p < 0.05$ and the first (second) is better (upscaled first).}}
\label{{tab:pvalues_other}}
\footnotesize
\begin{{ruledtabular}}
\begin{{tabular}}{{l{"c" * (len(DATASETS) * len(F2_METRICS))}}}
{header(F2_METRICS, "Pair")}
\midrule
{chr(10).join(f2)}
\end{{tabular}}
\end{{ruledtabular}}
\vspace{{0.8em}}
\begin{{ruledtabular}}
\begin{{tabular}}{{lcccccc}}
 & {f3_h1} \\
\cmidrule(lr){{2-4}} \cmidrule(lr){{5-7}}
\medsam{{}} & {f3_h2} \\
\midrule
{chr(10).join(f3_rows)}
\end{{tabular}}
\end{{ruledtabular}}
\end{{table*}}
"""
    write_tex("tabA4_pvalues", tex)


if __name__ == "__main__":
    main()
