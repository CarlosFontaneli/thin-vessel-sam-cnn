"""Table II (tab:global_baseline): overall segmentation performance (Dice, centerline recall, centerline
precision), five models.

MedSAM on DRIVE and VessMap with the upscaled protocol. Values are mean ± standard deviation over test images, in %,
one decimal. Rows: dataset and metric; columns: models. Bold: the highest mean of the row and every model
not significantly different from it (Dice from family F1, centerline recall and precision from family
F2 of ``all_tests.csv``).
Output: ``paper/manuscript/figures/tab01_global_baseline.tex``.
"""

from common import (
    COMPARISON_CONFIGS,
    CONFIGS,
    DATASETS,
    MARKS,
    ds_label,
    load_per_image,
    load_tests,
    means,
    pd,
    pm,
    save_values,
    sds,
    test_result,
    write_tex,
)

METRICS = [
    ("dice", "Dice"),
    ("centerline_recall", r"$R_{\mathrm{cl}}$"),
    ("centerline_precision", r"$P_{\mathrm{cl}}$"),
]
MACROS = {
    "lwnet": r"\lwnet{}",
    "convunext": r"\convunext{}",
    "convnext": r"\convnext{}",
    "litemedsam": r"\litemedsam{}",
    "medsam": r"\medsam{}",
}


def main() -> None:
    df = load_per_image()
    tests = load_tests()
    rows, body = [], []
    for ds in DATASETS:
        for k, (metric, label) in enumerate(METRICS):
            mean = means(df, metric).loc[COMPARISON_CONFIGS, ds]
            sd = sds(df, metric).loc[COMPARISON_CONFIGS, ds]
            best = mean.idxmax()
            cells = []
            for cfg in COMPARISON_CONFIGS:
                if cfg == best:
                    bold, p = "best", None
                else:
                    t = test_result(tests, ds, metric, cfg, best, mean[cfg], mean[best])
                    bold, p = (False if t["significant"] else "tie"), t["p_holm"]
                cells.append(pm(100 * mean[cfg], 100 * sd[cfg], bold))
                rows.append(
                    {
                        "dataset": ds,
                        "metric": metric,
                        "configuration": cfg,
                        "mean_percent": 100 * mean[cfg],
                        "sd_percent": 100 * sd[cfg],
                        "highest_mean": cfg == best,
                        "p_holm_vs_highest": p,
                        "bold": bool(bold),
                    }
                )
            first = ds_label(ds, len(METRICS)) if k == 0 else ""
            body.append(f"{first} & {label} & " + " & ".join(cells) + r" \\")
        body.append(r"\midrule")
    body.pop()
    save_values(pd.DataFrame(rows), "tab01_global_baseline")

    models = " & ".join(MACROS[CONFIGS[c]["arch"]] for c in COMPARISON_CONFIGS)
    tex = rf"""% Generated by paper/figures_tables/tab01_global_baseline.py -- do not edit by hand.
% Source: results/per_image_metrics.csv (MedSAM DRIVE/VessMap upscaled protocol); tests from
% outputs/statistics/all_tests.csv.
\begin{{table*}}[tbp]
\caption{{Overall segmentation performance. {MARKS} (per row).}}
\label{{tab:global_baseline}}
\begin{{ruledtabular}}
\begin{{tabular}}{{ll{"c" * len(COMPARISON_CONFIGS)}}}
 & & \multicolumn{{3}}{{c}}{{CNN}} & \multicolumn{{2}}{{c}}{{Fine-tuned}} \\
\cmidrule(lr){{3-5}} \cmidrule(lr){{6-7}}
Dataset & Metric & {models} \\
\midrule
{chr(10).join(body)}
\end{{tabular}}
\end{{ruledtabular}}
\end{{table*}}
"""
    write_tex("tab01_global_baseline", tex)


if __name__ == "__main__":
    main()
