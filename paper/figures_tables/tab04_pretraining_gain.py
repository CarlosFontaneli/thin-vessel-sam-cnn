"""Table VIII (tab:pretraining_gain): the data of Fig. 6, effect of pre-training on LiteMedSAM and MedSAM.

For each dataset, metric of Fig. 6 (Dice, thin-vessel recall, thin-vessel precision) and transformer-based model:
the mean ± standard deviation over test images of the fine-tuned and of the from-scratch run, and the gain
from pre-training (fine-tuned minus from scratch, in percentage points, computed from the printed one-decimal
values), with an asterisk when the Wilcoxon test (``all_tests.csv``, family F1) finds the two significantly
different; next to them, the highest mean among the three CNNs (named by a superscript). Rows: dataset and metric
(so that the mean ± SD cells fit the page width). Every mean is checked against
``outputs/figures/plotted/fig05_pretraining.csv`` (run ``fig05_pretraining.py`` first).
Source: ``per_image_metrics.csv`` (via ``common.load_per_image``; MedSAM DRIVE/VessMap upscaled protocol).
Output: ``paper/manuscript/figures/tab04_pretraining_gain.tex``.
"""

from common import (
    DATASETS,
    MARKS,
    PLOTTED_DIR,
    bold_group,
    ds_label,
    load_per_image,
    load_tests,
    means,
    np,
    pd,
    pm,
    read_table,
    save_values,
    sds,
    signed_delta,
    test_result,
    write_tex,
)

CNNS = ["lwnet_scratch", "convunext_scratch", "convnext_scratch"]
CNN_SHORT = {"lwnet_scratch": "L", "convunext_scratch": "U", "convnext_scratch": "N"}
PAIRS = [
    ("litemedsam", "litemedsam_pretrained", "litemedsam_scratch", r"\litemedsam{}"),
    ("medsam", "medsam_pretrained", "medsam_scratch", r"\medsam{}"),
]
METRICS = [
    ("dice", "Dice"),
    ("thin_vessel_recall", r"$\thinrecall$"),
    ("thin_vessel_precision", r"$P_{\mathrm{thin}}$"),
]


def main() -> None:
    df = load_per_image()
    tests = load_tests()
    fig5 = read_table(PLOTTED_DIR / "fig05_pretraining.csv").set_index(["metric", "dataset", "configuration"])
    rows, body = [], []
    for ds in DATASETS:
        for k, (metric, label) in enumerate(METRICS):
            m = means(df, metric) * 100
            sd = sds(df, metric) * 100
            for cfg in CNNS + [c for _, ft, sc, _ in PAIRS for c in (ft, sc)]:
                if not np.isclose(m.loc[cfg, ds], 100 * fig5.loc[(metric, ds, cfg), "mean"]):
                    raise ValueError(f"{cfg} on {ds}, {metric}: differs from the Fig. 6 data.")
            printed = m[ds].round(1)
            best = printed.loc[CNNS].idxmax()
            if (printed.loc[CNNS] == printed[best]).sum() > 1:
                raise ValueError(f"Tie between CNNs on {ds}, {metric}.")
            cells = []
            row_vals = {c: (c, m.loc[c, ds] / 100) for _, ft, sc, _ in PAIRS for c in (ft, sc)}
            row_vals[best] = (best, m.loc[best, ds] / 100)
            bold = bold_group(tests, ds, metric, row_vals)
            for arch, ft, sc, _ in PAIRS:
                gain = printed[ft] - printed[sc]
                if abs(gain - (m.loc[ft, ds] - m.loc[sc, ds])) > 0.1:
                    raise ValueError(f"Rounded gain far from the unrounded one: {arch}, {ds}, {metric}.")
                t = test_result(tests, ds, metric, ft, sc, m.loc[ft, ds] / 100, m.loc[sc, ds] / 100)
                cells += [
                    pm(m.loc[ft, ds], sd.loc[ft, ds], bold[ft]),
                    pm(m.loc[sc, ds], sd.loc[sc, ds], bold[sc]),
                    signed_delta(gain, t["significant"]),
                ]
                rows.append(
                    {
                        "dataset": ds,
                        "metric": metric,
                        "model": arch,
                        "fine_tuned": m.loc[ft, ds],
                        "fine_tuned_sd": sd.loc[ft, ds],
                        "from_scratch": m.loc[sc, ds],
                        "from_scratch_sd": sd.loc[sc, ds],
                        "gain_printed_pp": gain,
                        "p_holm": t["p_holm"],
                        "significant": t["significant"],
                        "best_cnn": best,
                        "best_cnn_value": m.loc[best, ds],
                        "best_cnn_sd": sd.loc[best, ds],
                    }
                )
            cells.append(pm(m.loc[best, ds], sd.loc[best, ds], bold[best]) + rf"\textsuperscript{{{CNN_SHORT[best]}}}")
            first = ds_label(ds, len(METRICS)) if k == 0 else ""
            body.append(f"{first} & {label} & " + " & ".join(cells) + r" \\")
        body.append(r"\midrule")
    body.pop()
    save_values(pd.DataFrame(rows), "tab04_pretraining_gain")

    header2 = " & ".join(r"FT & Scratch & $\Delta$" for _ in PAIRS)
    header1 = " & ".join(rf"\multicolumn{{3}}{{c}}{{{macro}}}" for *_, macro in PAIRS)
    tex = rf"""% Generated by paper/figures_tables/tab04_pretraining_gain.py -- do not edit by hand.
% Source: results/per_image_metrics.csv (MedSAM DRIVE/VessMap upscaled protocol); the values plotted in Fig. 6
% (checked against outputs/figures/plotted/fig05_pretraining.csv); tests from outputs/statistics/all_tests.csv.
\begin{{table*}}[tbp]
\caption{{Effect of pre-training, the data of Fig.~\ref{{fig:pretraining}}: \litemedsam{{}} and \medsam{{}} fine-tuned
(FT) and from scratch, and the best CNN (letters as in Table~\ref{{tab:medsam_vs_cnn}}); $\Delta$: FT minus Scratch,
with $^{{*}}$ when FT and Scratch differ significantly. {MARKS} (per row).}}
\label{{tab:pretraining_gain}}
\begin{{ruledtabular}}
\begin{{tabular}}{{ll{"ccc" * len(PAIRS)}c}}
 & & {header1} & \\
\cmidrule(lr){{3-5}} \cmidrule(lr){{6-8}}
Dataset & Metric & {header2} & CNN \\
\midrule
{chr(10).join(body)}
\end{{tabular}}
\end{{ruledtabular}}
\end{{table*}}
"""
    write_tex("tab04_pretraining_gain", tex)


if __name__ == "__main__":
    main()
